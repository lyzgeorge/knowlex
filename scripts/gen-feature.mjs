#!/usr/bin/env node
import { mkdirSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)
const projectRoot = resolve(__dirname, '..')

const rawName = process.argv[2]

if (!rawName) {
  console.error('Usage: pnpm gen:feature <feature-name>')
  process.exit(1)
}

const normalized = rawName.trim()
if (!/^[a-z0-9-]+$/i.test(normalized)) {
  console.error('Feature name must be alphanumeric/kebab-case (letters, numbers, hyphen).')
  process.exit(1)
}

const featureDir = join(projectRoot, 'src', 'renderer', 'features', normalized)
const storesDir = join(projectRoot, 'src', 'renderer', 'stores')
const hooksDir = join(projectRoot, 'src', 'renderer', 'hooks')

const toPascal = (input) =>
  input
    .split(/[-_\s]+/)
    .filter(Boolean)
    .map((segment) => segment.charAt(0).toUpperCase() + segment.slice(1))
    .join('')

const pascalName = toPascal(normalized)
const camelName = pascalName.charAt(0).toLowerCase() + pascalName.slice(1)

const componentFile = join(featureDir, `${pascalName}Feature.tsx`)
const featureIndexFile = join(featureDir, 'index.ts')
const storeFile = join(storesDir, `${camelName}Store.ts`)
const hookFile = join(hooksDir, `use${pascalName}.ts`)

const ensureDir = (path) => {
  if (!existsSync(path)) {
    mkdirSync(path, { recursive: true })
  }
}

ensureDir(featureDir)
ensureDir(storesDir)
ensureDir(hooksDir)

const writeFileSafely = (path, contents) => {
  if (existsSync(path)) {
    console.warn(`Skip existing file: ${path}`)
    return
  }
  writeFileSync(path, contents, 'utf8')
  console.log(`Created ${path.replace(projectRoot + '/', '')}`)
}

writeFileSafely(
  componentFile,
  `import { Stack, Text } from '@chakra-ui/react'\n\nexport interface ${pascalName}FeatureProps {\n  // TODO: declare props required by the feature root component\n}\n\n/**\n * Feature root component generated by gen:feature.\n * Replace placeholder content with real UI.\n */\nexport function ${pascalName}Feature(_props: ${pascalName}FeatureProps) {\n  return (\n    <Stack spacing={4} p={6}>\n      <Text fontSize=\"lg\" fontWeight=\"semibold\">${pascalName} feature scaffold</Text>\n      <Text color=\"gray.500\">Edit ${pascalName}Feature.tsx to implement feature UI.</Text>\n    </Stack>\n  )\n}\n\nexport default ${pascalName}Feature\n`
)

writeFileSafely(
  featureIndexFile,
  `export { ${pascalName}Feature } from './${pascalName}Feature'\n`
)

writeFileSafely(
  storeFile,
  `import { create } from 'zustand'\n\ninterface ${pascalName}State {\n  isInitializing: boolean\n}\n\ninterface ${pascalName}Actions {\n  setInitializing: (value: boolean) => void\n}\n\nexport type ${pascalName}Store = ${pascalName}State & ${pascalName}Actions\n\nexport const use${pascalName}Store = create<${pascalName}Store>((set) => ({\n  isInitializing: true,\n  setInitializing: (value) => set({ isInitializing: value })\n}))\n`
)

writeFileSafely(
  hookFile,
  `import { useMemo } from 'react'\nimport { use${pascalName}Store } from '@renderer/stores/${camelName}Store'\n\n/**\n * Domain hook scaffolding generated by gen:feature.\n * Replace memoised snapshot logic with real business interactions.\n */\nexport function use${pascalName}() {\n  const isInitializing = use${pascalName}Store((state) => state.isInitializing)\n  const setInitializing = use${pascalName}Store((state) => state.setInitializing)\n\n  return useMemo(() => ({ isInitializing, setInitializing }), [isInitializing, setInitializing])\n}\n`
)
